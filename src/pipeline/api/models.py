from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


class ErrorResponse(BaseModel):
    detail: str


class MovieItem(BaseModel):
    item_id: int
    title: str
    genres: str


class HistoryResponse(BaseModel):
    user_id: int
    recent_history: list[MovieItem]


class RecommendationItem(BaseModel):
    item_id: int
    title: str
    genres: str
    score: float | None = None


class RecommendationResponse(BaseModel):
    user_id: int
    model_name: str
    recommendations: list[RecommendationItem]


class ExplainedItem(BaseModel):
    item_id: int
    title: str
    genres: str
    reason: str


class RAGResponse(BaseModel):
    user_id: int
    rationale: str = Field(description="Natural language explanation generated by the LLM.")
    recommendations: list[ExplainedItem] = Field(
        default_factory=list,
        description="Structured recommendations with one grounded explanation per item.",
    )


class SimilarItemsResponse(BaseModel):
    item_id: int
    source_item: MovieItem
    similar_items: list[RecommendationItem]


class RankingParameter(BaseModel):
    name: str
    importance: str
    description: str


class TransparencyResponse(BaseModel):
    title: str
    regulation: str
    main_parameters: list[RankingParameter]
    models_summary: dict[str, str]
    user_controls: list[str]
    dsa_compliance: str


class ErasureResponse(BaseModel):
    user_id: int
    status: str
    erased_at: str
    erased_cache_entries: int
    message: str


class BusinessRuleCreate(BaseModel):
    rule_id: str
    rule_type: str = Field(description="'exclude', 'boost', or 'pin'")
    item_ids: list[int] = Field(default_factory=list)
    genres: list[str] = Field(default_factory=list)
    value: float = Field(default=1.0)
    position: int | None = Field(default=None)
    start_date: str | None = Field(default=None)
    end_date: str | None = Field(default=None)
    priority: int = Field(default=0)


class BusinessRuleResponse(BaseModel):
    rule_id: str
    rule_type: str
    item_ids: list[int]
    genres: list[str]
    value: float
    position: int | None
    start_date: str | None
    end_date: str | None
    priority: int
    is_active: bool


class ConflictResponse(BaseModel):
    rule_ids: list[str]
    conflict_type: str
    description: str


class RulesListResponse(BaseModel):
    rules: list[BusinessRuleResponse]
    conflicts: list[ConflictResponse]


class EventItem(BaseModel):
    user_id: int = Field(gt=0, description="Positive user identifier")
    item_id: int = Field(gt=0, description="Positive item identifier")
    event_type: str = Field(
        description=(
            "Event type: view, click, purchase, rating, thumbs_up, thumbs_down, not_interested"
        )
    )
    timestamp: datetime | None = Field(default=None, description="Optional UTC event timestamp")
    rating: float | None = Field(
        default=None, ge=0.5, le=5.0, description="Rating value (0.5 to 5.0) for rating events"
    )
    metadata: dict[str, Any] = Field(default_factory=dict, description="Custom event metadata")


class EventBatchRequest(BaseModel):
    events: list[EventItem] = Field(min_length=1, description="Batch of events to ingest")
    idempotency_key: str | None = Field(
        default=None, description="Optional payload idempotency key"
    )


class EventBatchResponse(BaseModel):
    status: str = "success"
    ingested_count: int
    is_idempotent_replay: bool = False
    idempotency_key: str | None = None
