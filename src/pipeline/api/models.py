from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field, model_validator


class ErrorResponse(BaseModel):
    detail: str


class MovieItem(BaseModel):
    item_id: int
    title: str
    genres: str


class HistoryResponse(BaseModel):
    user_id: int
    recent_history: list[MovieItem]


class RecommendationItem(BaseModel):
    item_id: int
    title: str
    genres: str
    score: float | None = None


class RecommendationResponse(BaseModel):
    user_id: int
    model_name: str
    recommendations: list[RecommendationItem]


class ExplainedItem(BaseModel):
    item_id: int
    title: str
    genres: str
    reason: str


class RAGResponse(BaseModel):
    user_id: int
    rationale: str = Field(description="Natural language explanation generated by the LLM.")
    recommendations: list[ExplainedItem] = Field(
        default_factory=list,
        description="Structured recommendations with one grounded explanation per item.",
    )


class SimilarItemsResponse(BaseModel):
    item_id: int
    source_item: MovieItem
    similar_items: list[RecommendationItem]


class RankingParameter(BaseModel):
    name: str
    importance: str
    description: str


class TransparencyResponse(BaseModel):
    title: str
    regulation: str
    main_parameters: list[RankingParameter]
    models_summary: dict[str, str]
    user_controls: list[str]
    dsa_compliance: str


class ErasureResponse(BaseModel):
    user_id: int
    status: str
    erased_at: str
    erased_cache_entries: int
    message: str


class BusinessRuleCreate(BaseModel):
    rule_id: str
    rule_type: str = Field(description="'exclude', 'boost', or 'pin'")
    item_ids: list[int] = Field(default_factory=list)
    genres: list[str] = Field(default_factory=list)
    value: float = Field(default=1.0)
    position: int | None = Field(default=None)
    start_date: str | None = Field(default=None)
    end_date: str | None = Field(default=None)
    priority: int = Field(default=0)
    tenant_id: str = Field(default="default")


class BusinessRuleResponse(BaseModel):
    rule_id: str
    rule_type: str
    item_ids: list[int]
    genres: list[str]
    value: float
    position: int | None
    start_date: str | None
    end_date: str | None
    priority: int
    is_active: bool
    tenant_id: str = "default"


class ConflictResponse(BaseModel):
    rule_ids: list[str]
    conflict_type: str
    description: str


class RulesListResponse(BaseModel):
    rules: list[BusinessRuleResponse]
    conflicts: list[ConflictResponse]


class EventItem(BaseModel):
    user_id: int | None = Field(
        default=None, description="Positive user identifier (optional if session_id provided)"
    )
    session_id: str | None = Field(
        default=None, description="Optional anonymous session identifier"
    )
    tenant_id: str = Field(default="default", description="Tenant isolation identifier")
    item_id: int = Field(gt=0, description="Positive item identifier")
    event_type: str = Field(
        description=(
            "Event type: view, click, purchase, rating, thumbs_up, thumbs_down, not_interested"
        )
    )
    timestamp: datetime | None = Field(default=None, description="Optional UTC event timestamp")
    rating: float | None = Field(
        default=None, ge=0.5, le=5.0, description="Rating value (0.5 to 5.0) for rating events"
    )
    metadata: dict[str, Any] = Field(default_factory=dict, description="Custom event metadata")

    @model_validator(mode="after")
    def validate_identity(self) -> EventItem:
        if self.user_id is None and not self.session_id:
            raise ValueError("Either user_id or session_id must be provided.")
        if self.user_id is not None and self.user_id <= 0:
            raise ValueError("user_id must be a positive integer.")
        return self


class EventBatchRequest(BaseModel):
    events: list[EventItem] = Field(min_length=1, description="Batch of events to ingest")
    idempotency_key: str | None = Field(
        default=None, description="Optional payload idempotency key"
    )


class EventBatchResponse(BaseModel):
    status: str = "success"
    ingested_count: int
    is_idempotent_replay: bool = False
    idempotency_key: str | None = None


class VariantModel(BaseModel):
    name: str
    weight: float = 1.0
    model_type: str = "sasrec"
    params: dict[str, Any] = Field(default_factory=dict)


class ExperimentCreate(BaseModel):
    id: str
    name: str
    variants: list[VariantModel] = Field(min_length=2)
    description: str = ""
    tenant_id: str = "default"


class ExperimentResponse(BaseModel):
    id: str
    name: str
    variants: list[VariantModel]
    status: str
    created_at: str
    description: str = ""
    tenant_id: str = "default"


class VariantMetricsModel(BaseModel):
    variant_name: str
    exposures: int
    conversions: int
    conversion_rate: float


class UpliftResponse(BaseModel):
    experiment_id: str
    control: VariantMetricsModel
    treatment: VariantMetricsModel
    absolute_uplift: float
    relative_uplift_pct: float
    ci_lower: float
    ci_upper: float
    p_value: float
    is_significant: bool
    confidence_level: float = 0.95


class SampleSizeResponse(BaseModel):
    baseline_conversion: float
    minimum_detectable_effect: float
    required_sample_size_per_variant: int
    total_required_sample_size: int


class SessionEventRequest(BaseModel):
    item_id: int = Field(gt=0, description="Item identifier")
    event_type: str = Field(default="click", description="Event type, e.g. click, view, purchase")
    timestamp: datetime | None = Field(default=None, description="Optional UTC event timestamp")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Custom event metadata")


class SessionResponse(BaseModel):
    session_id: str
    item_ids: list[int]
    tenant_id: str = "default"
    created_at: str
    updated_at: str
    event_count: int
    metadata: dict[str, Any] = Field(default_factory=dict)


class SessionRecommendRequest(BaseModel):
    session_id: str | None = Field(default=None, description="Session identifier")
    item_ids: list[int] | None = Field(default=None, description="Explicit sequence of item IDs")
    k: int = Field(default=10, ge=1, le=100, description="Number of recommendations")
    exclude: str | None = Field(default=None, description="Comma-separated item IDs to exclude")
    genres: str | None = Field(default=None, description="Comma-separated genre filters")
    diversity: float = Field(default=0.0, ge=0.0, le=1.0, description="MMR diversity parameter")
